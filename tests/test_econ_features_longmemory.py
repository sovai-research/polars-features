def test_estimate_ffd_order_is_wired_and_clipped() -> None:
    d = estimate_ffd_order(arfima_noise(0.35, 4096, seed=2), bandwidth_exponent=0.7)
    assert 0.0 <= d <= 1.0
    assert d == pytest.approx(0.35, abs=0.12)
    # Clipping keeps the returned order legal for `ffd_weights`.
    rng = np.random.default_rng(9)
    anti = -np.diff(np.cumsum(rng.standard_normal(2048)))  # over-differenced
    assert estimate_ffd_order(anti) >= 0.0


def _long_memory_panel(n: int = 2048) -> pl.DataFrame:
    frames = []
    for name, d in (("slow", 0.4), ("fast", 0.05)):
        frames.append(
            pl.DataFrame(
                {
                    "entity": [name] * n,
                    "time": np.arange(n, dtype=np.int64),
                    "x": arfima_noise(d, n, seed=hash(name) % 1000),
                }
            )
        )
    return pl.concat(frames)


def test_long_memory_table_orders_entities_by_persistence() -> None:
    out = long_memory_table(
        _long_memory_panel(),
        "x",
        entity="entity",
        time="time",
        bandwidth_exponent=0.7,
    )
    rows = {r["entity"]: r for r in out.to_dicts()}
    assert rows["slow"]["d"] > rows["fast"]["d"]
    assert rows["slow"]["d_se"] > 0


def test_rolling_long_memory_features_are_trailing() -> None:
    out = rolling_long_memory_features(
        _long_memory_panel(n=600),
        "x",
        entity="entity",
        time="time",
        window=256,
    )
    col = out.get_column("x_d")
    assert col.head(255).is_null().all()
    assert col.slice(255, 50).is_not_null().all()


def test_auto_fracdiff_fits_per_entity_orders_on_train_only() -> None:
    df = _long_memory_panel()
    panel = PanelFrame(df, entity="entity", time="time")
    tr = AutoFracDiff(["x"], bandwidth_exponent=0.7).fit(panel)
    assert tr.orders_[("slow", "x")] > tr.orders_[("fast", "x")]
    out = tr.transform(panel).collect()
    assert "x_ffd" in out.columns
    assert out.get_column("x_ffd").is_not_null().sum() > 0


def test_auto_fracdiff_transform_uses_frozen_orders() -> None:
    df = _long_memory_panel()
    panel = PanelFrame(df, entity="entity", time="time")
    tr = AutoFracDiff(["x"], bandwidth_exponent=0.7).fit(panel)
    frozen = dict(tr.orders_)
    # Transforming a different (later) panel must not change the fitted orders.
    later = PanelFrame(df.filter(pl.col("time") >= 1024), entity="entity", time="time")
    tr.transform(later)
    assert tr.orders_ == frozen


def test_auto_fracdiff_rejects_negative_d_min() -> None:
    with pytest.raises(ValueError, match="diverges for"):
        AutoFracDiff(["x"], d_min=-0.5)
